#!/bin/bash

# HBVM Quick Start Script
# Host-Based Vulnerability Management System

set -e

echo "=== HBVM Quick Start Setup ==="
echo ""

# Color codes for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Function to print colored output
print_status() {
    echo -e "${GREEN}[INFO]${NC} $1"
}

print_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

print_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

print_step() {
    echo -e "${BLUE}[STEP]${NC} $1"
}

# Check if running as root
if [[ $EUID -eq 0 ]]; then
   print_error "This script should not be run as root"
   exit 1
fi

# Detect OS
if [[ "$OSTYPE" == "linux-gnu"* ]]; then
    OS="linux"
elif [[ "$OSTYPE" == "darwin"* ]]; then
    OS="macos"
else
    print_error "Unsupported operating system: $OSTYPE"
    exit 1
fi

print_status "Detected OS: $OS"

# Check prerequisites
check_command() {
    if ! command -v $1 &> /dev/null; then
        print_error "$1 is not installed. Please install it first."
        return 1
    else
        print_status "$1 is installed"
        return 0
    fi
}

print_step "Checking prerequisites..."

MISSING_DEPS=0

# Check Node.js
if ! check_command node; then
    print_warning "Please install Node.js 16+ from: https://nodejs.org/"
    MISSING_DEPS=1
fi

# Check Python
if ! check_command python3; then
    print_warning "Please install Python 3.8+ from: https://python.org/"
    MISSING_DEPS=1
fi

# Check Docker (optional)
if check_command docker; then
    DOCKER_AVAILABLE=1
    print_status "Docker is available for containerized deployment"
else
    DOCKER_AVAILABLE=0
    print_warning "Docker not found. Will use native installation."
fi

if [[ $MISSING_DEPS -eq 1 ]]; then
    print_error "Please install missing dependencies and run this script again."
    exit 1
fi

# Choose installation method
echo ""
echo "Choose installation method:"
echo "1) Docker Compose (Recommended)"
echo "2) Native Installation"
echo "3) Development Setup"

read -p "Enter your choice (1-3): " INSTALL_METHOD

case $INSTALL_METHOD in
    1)
        if [[ $DOCKER_AVAILABLE -eq 0 ]]; then
            print_error "Docker is not available. Please install Docker and Docker Compose."
            exit 1
        fi
        
        print_step "Setting up Docker Compose deployment..."
        
        # Generate secure passwords
        print_status "Generating secure passwords..."
        MONGO_ROOT_PASSWORD=$(openssl rand -base64 32 | tr -d "=+/" | cut -c1-25)
        HBVM_DB_PASSWORD=$(openssl rand -base64 32 | tr -d "=+/" | cut -c1-25)
        JWT_SECRET=$(openssl rand -base64 48 | tr -d "=+/" | cut -c1-64)
        AGENT_API_KEY=$(openssl rand -hex 32)
        
        # Create .env file
        cat > .env << EOF
# Generated by HBVM Quick Start
MONGO_ROOT_PASSWORD=$MONGO_ROOT_PASSWORD
HBVM_DB_PASSWORD=$HBVM_DB_PASSWORD
JWT_SECRET=$JWT_SECRET
AGENT_API_KEY=$AGENT_API_KEY
EOF
        
        print_status "Created .env file with secure passwords"
        
        # Create Docker init script
        mkdir -p docker
        cat > docker/mongodb-init.js << EOF
// MongoDB initialization script
db = db.getSiblingDB('hbvm');
db.createUser({
  user: 'hbvm_user',
  pwd: '$HBVM_DB_PASSWORD',
  roles: ['readWrite']
});
EOF
        
        # Start services
        print_step "Starting HBVM services with Docker Compose..."
        docker-compose up -d mongodb backend
        
        # Wait for services to be ready
        print_status "Waiting for services to start..."
        sleep 30
        
        # Test backend health
        if curl -f http://localhost:3000/api/health &> /dev/null; then
            print_status "Backend is running successfully!"
        else
            print_error "Backend failed to start. Check logs with: docker-compose logs backend"
            exit 1
        fi
        
        # Print setup information
        echo ""
        echo "=== HBVM Setup Complete ==="
        echo "Backend URL: http://localhost:3000"
        echo "API Health: http://localhost:3000/api/health"
        echo "Agent API Key: $AGENT_API_KEY"
        echo ""
        echo "Next steps:"
        echo "1. Configure agents with the API key above"
        echo "2. View logs: docker-compose logs -f"
        echo "3. Stop services: docker-compose down"
        ;;
        
    2)
        print_step "Setting up native installation..."
        
        # Check MongoDB
        if ! check_command mongod && ! check_command mongodb; then
            print_error "MongoDB is not installed. Please install MongoDB first."
            exit 1
        fi
        
        # Setup backend
        print_step "Setting up backend..."
        cd backend
        
        if [[ ! -f .env ]]; then
            cp .env.example .env
            print_status "Created .env file. Please edit it with your configuration."
        fi
        
        npm install
        print_status "Backend dependencies installed"
        
        # Setup agent
        print_step "Setting up agent..."
        cd ../agent
        
        python3 -m venv venv
        source venv/bin/activate
        pip install -r requirements.txt
        print_status "Agent dependencies installed"
        
        # Copy config if not exists
        if [[ ! -f config/config.local.yaml ]]; then
            cp config/config.yaml config/config.local.yaml
            print_status "Created agent config. Please edit config/config.local.yaml"
        fi
        
        cd ..
        
        echo ""
        echo "=== Native Installation Complete ==="
        echo ""
        echo "Next steps:"
        echo "1. Start MongoDB: sudo systemctl start mongod"
        echo "2. Edit backend/.env with your configuration"
        echo "3. Start backend: cd backend && npm start"
        echo "4. Edit agent/config/config.local.yaml"
        echo "5. Test agent: cd agent && source venv/bin/activate && python src/scanner.py --scan-only"
        ;;
        
    3)
        print_step "Setting up development environment..."
        
        # Setup backend
        cd backend
        npm install
        if [[ ! -f .env ]]; then
            cp .env.example .env
            # Set development defaults
            sed -i.bak 's/NODE_ENV=production/NODE_ENV=development/' .env
        fi
        
        # Setup agent
        cd ../agent
        python3 -m venv venv
        source venv/bin/activate
        pip install -r requirements.txt
        
        if [[ ! -f config/config.local.yaml ]]; then
            cp config/config.yaml config/config.local.yaml
        fi
        
        cd ..
        
        echo ""
        echo "=== Development Setup Complete ==="
        echo ""
        echo "Development commands:"
        echo "Backend: cd backend && npm run dev"
        echo "Agent test: cd agent && source venv/bin/activate && python src/scanner.py --scan-only --no-send"
        echo ""
        echo "Make sure MongoDB is running before starting the backend."
        ;;
        
    *)
        print_error "Invalid choice. Please run the script again."
        exit 1
        ;;
esac

echo ""
print_status "HBVM setup completed successfully!"
echo ""
echo "Documentation:"
echo "- Installation Guide: INSTALLATION.md"
echo "- API Documentation: http://localhost:3000/api"
echo "- Project README: README.md"
echo ""
echo "For support, check the logs and documentation."

exit 0